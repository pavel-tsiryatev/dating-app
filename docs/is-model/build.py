def h1(t): out.append(f"<h1>{t}</h1>")
def h2(t, brk=False): out.append(f'<h2{" class=\"brk\"" if brk else ""}>{t}</h2>')
def h3(t): out.append(f"<h3>{t}</h3>")
def p(t): out.append(f"<p>{t}</p>")
def logic(t): out.append(f"<p><b>Логическое описание.</b> {t}</p>")
def ul(items): out.append("<ul>" + "".join(f"<li>{i}</li>" for i in items) + "</ul>")
def ol(items): out.append("<ol>" + "".join(f"<li>{i}</li>" for i in items) + "</ol>")
def raw(t): out.append(t)


def fig(svg, caption):
    out.append(f'<figure>{svg}<figcaption>{caption}</figcaption></figure>')


def table(head, rows, cls="", widths=None):
    cg = ""
    if widths:
        cg = "<colgroup>" + "".join(f'<col style="width:{w}%">' for w in widths) + "</colgroup>"
    th = "".join(f"<th>{h}</th>" for h in head)
    tb = "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in rows)
    out.append(f'<table class="{cls}">{cg}<thead><tr>{th}</tr></thead><tbody>{tb}</tbody></table>')


def legend(t):
    out.append(f'<p class="legend">{t}</p>')


